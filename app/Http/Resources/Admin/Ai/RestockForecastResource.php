<?php

declare(strict_types=1);

namespace App\Http\Resources\Admin\Ai;

use App\Domain\Ai\Restock\RestockRow;
use App\Http\Resources\Admin\InventoryVariantPart;
use App\Http\Resources\ApiResource;
use App\Support\Money;
use Dedoc\Scramble\Attributes\SchemaName;
use Illuminate\Http\Request;

/**
 * Inventory › Restock forecast (Figma 540:83487). Every figure is the server's (rule 1); money
 * is a DECIMAL string (rule 6). Cost — `last_unit_cost`, `suggested_order_value` and the KPI —
 * needs catalog.view_cost, else null. `note` is today's cached AI note for exactly this forecast
 * (never generated by this GET); `note_blocked` says why none can be written.
 *
 * @property array{forecast: array{horizon: int, today: string, window_from: string, window_to: string, rows: list<RestockRow>, running_out: int, before_arrival: int, sales_at_risk: Money, suggested_order_value: Money}, note: array{sentences: list<string>, model: string, generated_at: string}|null, note_blocked: string|null} $resource
 */
#[SchemaName('RestockForecast')]
final class RestockForecastResource extends ApiResource
{
    /** @return array<string, mixed> */
    public function toArray(Request $request): array
    {
        $f = $this->resource['forecast'];
        $cost = InventoryVariantPart::canViewCost($request);

        return [
            /**
             * Days ahead: 7, 14 or 30.
             *
             * @var int
             */
            'horizon' => $f['horizon'],
            /**
             * Today in Dhaka, Y-m-d.
             *
             * @var string
             */
            'today' => $f['today'],
            /**
             * The sales window, Dhaka dates inclusive (30 days ending today).
             *
             * @var array{from: string, to: string, days: int}
             */
            'window' => ['from' => $f['window_from'], 'to' => $f['window_to'], 'days' => 30],
            /**
             * The KPI row.
             *
             * @var array{running_out: int, before_arrival: int, sales_at_risk: string, suggested_order_value: string|null}
             */
            'kpis' => [
                'running_out' => $f['running_out'],
                'before_arrival' => $f['before_arrival'],
                'sales_at_risk' => $f['sales_at_risk']->toDecimal(),
                'suggested_order_value' => $cost ? $f['suggested_order_value']->toDecimal() : null,
            ],
            /**
             * Variants that run out within the horizon plus their lead time, the soonest first.
             *
             * @var list<array{variant_id: int, product_id: int, product_name: string, product_name_bn: string|null, variant_name: string|null, variant_name_bn: string|null, sku: string, in_stock: int, units_sold: int, sells_per_day: string, runs_out_in_days: int, lead_time_days: int, lead_time_estimated: bool, open_po_quantity: int, suggested_order: int, units_short: int, confidence: 'high'|'medium'|'low', price: string, sales_at_risk: string, supplier: array{id: int, name: string}|null, last_unit_cost: string|null, suggested_order_value: string|null}>
             */
            'rows' => array_map(static fn (RestockRow $r): array => [
                'variant_id' => $r->variantId,
                'product_id' => $r->productId,
                'product_name' => $r->productName,
                'product_name_bn' => $r->productNameBn,
                'variant_name' => $r->variantName,
                'variant_name_bn' => $r->variantNameBn,
                'sku' => $r->sku,
                'in_stock' => $r->inStock,
                'units_sold' => $r->unitsSold,
                'sells_per_day' => $r->sellsPerDay,
                'runs_out_in_days' => $r->runsOutInDays,
                'lead_time_days' => $r->leadTimeDays,
                'lead_time_estimated' => $r->leadTimeEstimated,
                'open_po_quantity' => $r->openPurchaseUnits,
                'suggested_order' => $r->suggestedOrder,
                'units_short' => $r->unitsShort,
                'confidence' => $r->confidence,
                'price' => $r->price->toDecimal(),
                'sales_at_risk' => $r->salesAtRisk->toDecimal(),
                'supplier' => $r->supplierId !== null && $r->supplierName !== null ? ['id' => $r->supplierId, 'name' => $r->supplierName] : null,
                'last_unit_cost' => $cost ? $r->lastUnitCost : null,
                'suggested_order_value' => $cost ? $r->suggestedOrderValue?->toDecimal() : null,
            ], $f['rows']),
            /**
             * Today's cached AI note for exactly these figures, if one was written.
             *
             * @var array{sentences: list<string>, model: string, generated_at: string}|null
             */
            'note' => $this->resource['note'],
            /**
             * Why no note can be written (`figures_not_shared`, `nothing_to_order`), else null.
             *
             * @var 'figures_not_shared'|'nothing_to_order'|null
             */
            'note_blocked' => $this->resource['note_blocked'],
        ];
    }
}
