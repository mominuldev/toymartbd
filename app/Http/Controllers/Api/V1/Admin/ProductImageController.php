<?php

declare(strict_types=1);

namespace App\Http\Controllers\Api\V1\Admin;

use App\Domain\Catalog\Actions\AttachMediaToProduct;
use App\Domain\Catalog\Actions\CropProductImage;
use App\Domain\Catalog\Actions\DeleteProductImage;
use App\Domain\Catalog\Actions\ReorderProductImages;
use App\Domain\Catalog\Actions\UpdateProductImage;
use App\Domain\Catalog\Actions\UploadProductImage;
use App\Domain\Catalog\Models\Product;
use App\Domain\Catalog\Models\ProductImage;
use App\Http\Controllers\Api\V1\ApiController;
use App\Http\Requests\Admin\Product\CropProductImageRequest;
use App\Http\Requests\Admin\Product\ReorderProductImagesRequest;
use App\Http\Requests\Admin\Product\StoreProductImageRequest;
use App\Http\Requests\Admin\Product\UpdateProductImageRequest;
use App\Http\Resources\Admin\ProductImageResource;
use Dedoc\Scramble\Attributes\Response as OpenApiResponse;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Resources\Json\AnonymousResourceCollection;
use Illuminate\Http\Response;

/**
 * A product's images (P4-CAT-06/07), nested under the product. Uploads are
 * validated by content and re-encoded; renditions (WebP + AVIF at
 * config('media.widths')) are generated by a queued job after commit, so a new or
 * re-cropped image is `processing_status: processing` with null `urls` until it is
 * `ready`. Reads need catalog.view; every write needs catalog.update.
 */
final class ProductImageController extends ApiController
{
    /** `GET /products/{product}/images` — ordered by position. */
    public function index(Product $product): AnonymousResourceCollection
    {
        $this->authorize('view', $product);

        return ProductImageResource::collection($product->images()->get());
    }

    /**
     * `POST /products/{product}/images` — `multipart/form-data`; appended last, primary
     * when it is the product's first image. 201 with the image (`processing`). With
     * `media_id` instead of `file`, attaches an existing library image (no re-encode).
     */
    #[OpenApiResponse(422, 'Not a JPEG/PNG/WebP/AVIF by content, over 10 MB or 8000 px, an embedded payload, or undecodable (`validation-error` on `file`); with `media_id`: not an image, already in the gallery, or the gallery is full (`validation-error` on `media_id`)')]
    public function store(StoreProductImageRequest $request, Product $product, UploadProductImage $upload, AttachMediaToProduct $attach): JsonResponse
    {
        $mediaId = $request->mediaId();
        $attributes = $request->imageAttributes();

        $image = $mediaId !== null
            ? $attach->handle($product, $mediaId, array_intersect_key($attributes, array_flip(['alt_text', 'alt_text_bn', 'variant_id'])))
            : $upload->handle($product, $request->uploadedPath(), $attributes);

        return (new ProductImageResource($image))->response()->setStatusCode(201);
    }

    /** `PATCH /products/{product}/images/{image}` — alt text, variant, primary. */
    public function update(UpdateProductImageRequest $request, Product $product, ProductImage $image, UpdateProductImage $updateImage): ProductImageResource
    {
        return new ProductImageResource($updateImage->handle($image, $request->changes()));
    }

    /** `POST /products/{product}/images/{image}/crop` — re-crops; the image returns to `processing`. */
    public function crop(CropProductImageRequest $request, Product $product, ProductImage $image, CropProductImage $cropImage): ProductImageResource
    {
        return new ProductImageResource($cropImage->handle($image, $request->rectangle()));
    }

    /** `POST /products/{product}/images/reorder` — returns the images in the new order. */
    public function reorder(ReorderProductImagesRequest $request, Product $product, ReorderProductImages $reorder): AnonymousResourceCollection
    {
        $reorder->handle($product, $request->ids());

        return ProductImageResource::collection($product->images()->get());
    }

    /** `DELETE /products/{product}/images/{image}` — files are removed after commit. */
    public function destroy(Product $product, ProductImage $image, DeleteProductImage $deleteImage): Response
    {
        $this->authorize('update', $product);

        $deleteImage->handle($image);

        return response()->noContent();
    }
}
