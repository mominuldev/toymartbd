// Regenerates components/icons/paths.ts from the Phosphor icon set already installed at the repo
// root (@phosphor-icons/react, the admin's dependency). Path data is copied, never hand-written
// (UI-UX spec §3.6). Regular weight, 256 grid. Run from the repo root:
//   node toymartbd-app/storefront/scripts/extract-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const ICONS = {
    house: 'House',
    squaresFour: 'SquaresFour',
    magnifyingGlass: 'MagnifyingGlass',
    shoppingCart: 'ShoppingCart',
    user: 'User',
    heart: 'Heart',
    caretDown: 'CaretDown',
    phone: 'Phone',
    whatsappLogo: 'WhatsappLogo',
    envelopeSimple: 'EnvelopeSimple',
    wrench: 'Wrench',
    arrowClockwise: 'ArrowClockwise',
    checkCircle: 'CheckCircle',
    mapPin: 'MapPin',
};

const require = createRequire(import.meta.url);
const pkgJson = require.resolve('@phosphor-icons/react/package.json', { paths: [process.cwd()] });
const version = JSON.parse(readFileSync(pkgJson, 'utf8')).version;
const defs = join(dirname(pkgJson), 'dist', 'defs');

const entries = Object.entries(ICONS).map(([key, name]) => {
    const source = readFileSync(join(defs, `${name}.es.js`), 'utf8');
    const block = source.split('"regular"')[1]?.split(/\n\s*\],?\n/)[0];
    if (!block) throw new Error(`No regular weight in ${name}`);
    const paths = [...block.matchAll(/d: "([^"]+)"/g)].map((m) => m[1]);
    if (paths.length === 0) throw new Error(`No path data in ${name}`);
    return `    ${key}: ${JSON.stringify(paths)},`;
});

const out = `// GENERATED by scripts/extract-icons.mjs from @phosphor-icons/react ${version} (regular weight,
// 256 × 256 grid). Do not edit by hand; add the icon to the script and re-run it.
export const iconPaths = {
${entries.join('\n')}
} as const satisfies Record<string, readonly string[]>;

export type IconName = keyof typeof iconPaths;
`;
writeFileSync(new URL('../components/icons/paths.ts', import.meta.url), out);
console.log(`wrote ${entries.length} icons`);
