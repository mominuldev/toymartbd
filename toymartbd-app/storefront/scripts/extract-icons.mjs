const require = createRequire(import.meta.url);
const pkgJson = require.resolve('@phosphor-icons/react/package.json', { paths: [process.cwd()] });
const version = JSON.parse(readFileSync(pkgJson, 'utf8')).version;
const defs = join(dirname(pkgJson), 'dist', 'defs');

const entries = Object.entries(ICONS).map(([key, spec]) => {
    const [name, weight = 'regular'] = spec.split(':');
    const source = readFileSync(join(defs, `${name}.es.js`), 'utf8');
    const block = source.split(`"${weight}"`)[1]?.split(/\n\s*\],?\n/)[0];
    if (!block) throw new Error(`No ${weight} weight in ${name}`);
    const paths = [...block.matchAll(/d: "([^"]+)"/g)].map((m) => m[1]);
    if (paths.length === 0) throw new Error(`No path data in ${name}`);
    return `    ${key}: ${JSON.stringify(paths)},`;
});

const out = `// GENERATED by scripts/extract-icons.mjs from @phosphor-icons/react ${version} (regular weight unless
// the key ends in Fill; 256 × 256 grid). Do not edit by hand; add the icon to the script and re-run it.
export const iconPaths = {
${entries.join('\n')}
} as const satisfies Record<string, readonly string[]>;

export type IconName = keyof typeof iconPaths;
`;
writeFileSync(new URL('../components/icons/paths.ts', import.meta.url), out);
console.log(`wrote ${entries.length} icons`);
