import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import type { Schema } from '@toymart/api-types';
import { api, apiLocale, ApiError, csrfToken, isProblem } from '@/lib/api';

export type ProductImage = Schema<'ProductImage'>;
export type CropRect = { x: number; y: number; width: number; height: number };
export type ImagePatch = { alt_text?: string | null; alt_text_bn?: string | null; variant_id?: number | null; is_primary?: true };

/** Client-side pre-check only (UX). The server sniffs the real type and is authoritative. */
export const ACCEPTED_TYPES = ['image/jpeg', 'image/png', 'image/webp', 'image/avif'] as const;
export const MAX_BYTES = 10 * 1024 * 1024;
export const MAX_IMAGES = 10;

export const imageKeys = {
    product: (productId: number) => ['products', productId] as const,
    list: (productId: number) => ['products', productId, 'images'] as const,
};

const base = (productId: number) => `/products/${productId}/images`;

export function useProductImages(productId: number) {
    return useQuery({
        queryKey: imageKeys.list(productId),
        queryFn: () => api<{ data: ProductImage[] }>(base(productId)).then((r) => r.data),
        // Renditions are generated by a queued job: poll while any image is still processing.
        refetchInterval: (query) => (query.state.data?.some((i) => i.processing_status === 'processing') ? 2000 : false),
    });
}

/** After any image write the product (its image list, publish checks) is stale too. */
export function useInvalidateImages(productId: number) {
    const client = useQueryClient();
    return () => client.invalidateQueries({ queryKey: imageKeys.product(productId) });
}

export function useUpdateImage(productId: number) {
    const invalidate = useInvalidateImages(productId);
    return useMutation({
        mutationFn: ({ id, patch }: { id: number; patch: ImagePatch }) =>
            api<ProductImage>(`${base(productId)}/${id}`, { method: 'PATCH', body: JSON.stringify(patch) }),
        onSettled: invalidate,
    });
}

export function useReorderImages(productId: number) {
    const client = useQueryClient();
    const invalidate = useInvalidateImages(productId);
    return useMutation({
        mutationFn: (ids: number[]) => api<{ data: ProductImage[] }>(`${base(productId)}/reorder`, { method: 'POST', body: JSON.stringify({ ids }) }),
        // Optimistic: the tiles move at once; a failure refetches the server order.
        onMutate: (ids) => {
            const key = imageKeys.list(productId);
            const current = client.getQueryData<ProductImage[]>(key);
            if (current) {
                const byId = new Map(current.map((i) => [i.id, i]));
                client.setQueryData(key, ids.map((id, position) => ({ ...byId.get(id)!, position })));
            }
        },
        onSettled: invalidate,
    });
}

export function useDeleteImage(productId: number) {
    const invalidate = useInvalidateImages(productId);
    return useMutation({
        mutationFn: (id: number) => api<void>(`${base(productId)}/${id}`, { method: 'DELETE' }),
        onSettled: invalidate,
    });
}

export function useCropImage(productId: number) {
    const invalidate = useInvalidateImages(productId);
    return useMutation({
        mutationFn: ({ id, rect }: { id: number; rect: CropRect }) =>
            api<ProductImage>(`${base(productId)}/${id}/crop`, { method: 'POST', body: JSON.stringify(rect) }),
        onSettled: invalidate,
    });
}

/**
 * Multipart upload over XMLHttpRequest — fetch cannot report upload progress. Same
 * contract as `api()`: cookie session, CSRF header, RFC 9457 problems as ApiError.
 */
export function uploadImage(productId: number, file: File, onProgress: (loaded: number, total: number) => void): Promise<ProductImage> {
    return new Promise((resolve, reject) => {
        const xhr = new XMLHttpRequest();
        xhr.open('POST', `/api/v1/admin${base(productId)}`);
        xhr.withCredentials = true;
        xhr.setRequestHeader('Accept', 'application/json');
        xhr.setRequestHeader('Accept-Language', apiLocale());
        xhr.setRequestHeader('X-XSRF-TOKEN', csrfToken());
        xhr.upload.onprogress = (event) => {
            if (event.lengthComputable) onProgress(event.loaded, event.total);
        };
        xhr.onerror = () => reject(new ApiError(0, { type: 'about:blank', title: 'Network error', status: 0 }));
        xhr.onload = () => {
            let payload: unknown = null;
            try {
                payload = JSON.parse(xhr.responseText);
            } catch {
                payload = null;
            }
            if (xhr.status >= 200 && xhr.status < 300) resolve(payload as ProductImage);
            else reject(new ApiError(xhr.status, isProblem(payload) ? payload : { type: 'about:blank', title: xhr.statusText || 'Upload failed', status: xhr.status }));
        };
        const body = new FormData();
        body.append('file', file);
        xhr.send(body);
    });
}
