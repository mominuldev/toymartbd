import { useId, useMemo, useState, type ChangeEvent, type ReactNode } from 'react';
import { ArrowCounterClockwiseIcon, PlusIcon, TrashIcon, WarningCircleIcon, XIcon } from '@phosphor-icons/react';
import { useI18n } from '@/i18n/I18nProvider';
import { Button, buttonClass } from '@/components/ui/Button';
import { controlHeight, inputClass, monoInputClass } from '@/components/ui/Field';
import { IconButton } from '@/components/ui/IconButton';
import { Input } from '@/components/ui/Input';
import { Select } from '@/components/ui/Select';
import type { Attribute } from '../attributes/api';
import { TAKA, Toggle } from './parts';
import { emptyRow, labelFor, type Combination, type MatrixRow, type MatrixState, type PlacedErrors, type VariantFields } from './document';

/** App\Domain\Catalog\Services\ProductDocumentValidator::MAX_VARIANTS — the server enforces it; this only warns early. */
export const MAX_VARIANTS = 100;
const MAX_ATTRIBUTES = 3;

type BulkField = 'price' | 'cost_price' | 'weight_grams';

type Props = {
    /** Variant-defining attributes with their values (GET /attributes). */
    attributes: Attribute[];
    value: MatrixState;
    combos: Combination[];
    onChange: (next: MatrixState) => void;
    errors: PlacedErrors['rows'];
    matrixErrors: string[];
    /** catalog.view_cost — without it the Cost column does not exist. */
    canCost: boolean;
    /** Price edits (and new priced variants) need catalog.update_price on an existing product. */
    canPrice: boolean;
    disabled: boolean;
};

/**
 * VariantMatrixEditor (A9, Figma 201:1201): pick the variant-defining attributes and
 * their values; one row per combination with its own price, compare-at, cost, SKU,
 * barcode, weight and on/off. SKUs left blank are generated by the server. A removed
 * value archives its variants on save; adding it back restores them.
 */
export function VariantMatrixEditor({ attributes, value, combos, onChange, errors, matrixErrors, canCost, canPrice, disabled }: Props) {
    const { t, locale } = useI18n();
    const bn = locale === 'bn';
    const [selected, setSelected] = useState<Set<string>>(new Set());
    const [bulkField, setBulkField] = useState<BulkField>(canPrice ? 'price' : 'weight_grams');
    const [bulkValue, setBulkValue] = useState('');
    const bulkId = useId();

    const name = (a: { name: string; name_bn: string | null }) => (bn ? (a.name_bn ?? a.name) : a.name);
    const comboKeys = useMemo(() => new Set(combos.map((c) => c.key)), [combos]);
    const rowOf = (combo: Combination): MatrixRow => value.rows[combo.key] ?? emptyRow(combo.valueIds);
    const outside = Object.entries(value.rows).filter(([key, row]) => row.id !== null && !comboKeys.has(key));
    const usedAttributes = new Set(value.options.map((o) => o.attribute_id));
    const freeAttributes = attributes.filter((a) => !usedAttributes.has(a.id));
    const canAddAttribute = value.options.length < MAX_ATTRIBUTES && freeAttributes.length !== 0;
    const tooMany = combos.length > MAX_VARIANTS;
    const enabledCount = combos.filter((c) => rowOf(c).status === 'active').length;

    const setOptions = (options: MatrixState['options']) => onChange({ ...value, options });
    const patchRow = (combo: Combination, patch: Partial<MatrixRow>) =>
        onChange({ ...value, rows: { ...value.rows, [combo.key]: { ...rowOf(combo), ...patch } } });

    const addValue = (attributeId: number, valueId: number) =>
        setOptions(value.options.map((o) => (o.attribute_id === attributeId ? { ...o, value_ids: [...o.value_ids, valueId] } : o)));
    const removeValue = (attributeId: number, valueId: number) =>
        setOptions(value.options.map((o) => (o.attribute_id === attributeId ? { ...o, value_ids: o.value_ids.filter((id) => id !== valueId) } : o)));

    const targets = selected.size > 0 ? combos.filter((c) => selected.has(c.key)) : combos;
    const applyBulk = () => {
        const rows = { ...value.rows };
        for (const combo of targets) rows[combo.key] = { ...rowOf(combo), [bulkField]: bulkValue.trim() };
        onChange({ ...value, rows });
    };

    const allSelected = combos.length > 0 && combos.every((c) => selected.has(c.key));
    const toggleAll = () => setSelected(allSelected ? new Set() : new Set(combos.map((c) => c.key)));
    const toggleOne = (key: string) =>
        setSelected((current) => {
            const next = new Set(current);
            if (next.has(key)) next.delete(key);
            else next.add(key);
            return next;
        });

    const bulkFields: { value: BulkField; label: string; allowed: boolean }[] = [
        { value: 'price', label: t('products.field.price'), allowed: canPrice },
        { value: 'cost_price', label: t('products.field.cost'), allowed: canCost },
        { value: 'weight_grams', label: t('products.field.weight'), allowed: true },
    ];
    const columnCount = 8 + (canCost ? 1 : 0);

    const cell = (combo: Combination, row: MatrixRow, field: keyof VariantFields, label: string) => {
        const error = errors[combo.key]?.[field];
        const common = {
            'aria-label': `${label} — ${bn ? combo.labelBn : combo.label}`,
            value: row[field],
            disabled,
            onChange: (e: ChangeEvent<HTMLInputElement>) => patchRow(combo, { [field]: e.target.value }),
        };
        const priceField = field === 'price' || field === 'compare_at_price';
        if (priceField || field === 'cost_price') {
            const locked = priceField && !canPrice;
            return (
                <div className="w-28">
                    <Input
                        {...common}
                        size="sm"
                        prefix={TAKA}
                        inputMode="decimal"
                        autoComplete="off"
                        aria-invalid={error ? true : undefined}
                        readOnly={locked}
                        className={`[&_input]:text-end [&_input]:tabular-nums ${locked ? 'bg-subtle!' : ''}`}
                    />
                </div>
            );
        }
        const mono = field === 'sku' || field === 'barcode';
        return (
            <div className={field === 'sku' ? 'w-52' : field === 'barcode' ? 'w-36' : 'w-24'}>
                <input
                    {...common}
                    aria-invalid={error ? true : undefined}
                    autoComplete="off"
                    spellCheck={false}
                    inputMode={field === 'weight_grams' ? 'numeric' : undefined}
                    placeholder={field === 'sku' && row.id === null ? t('products.matrix.skuAuto') : undefined}
                    className={`${controlHeight.sm} ${mono ? monoInputClass : `${inputClass} text-end tabular`}`}
                />
            </div>
        );
    };

    return (
        <section aria-labelledby={`${bulkId}-title`} className="flex flex-col overflow-hidden rounded-md border border-line-default bg-surface shadow-e1">
            <div className="flex flex-col gap-2.5 px-5 pt-5 pb-4">
                <h2 id={`${bulkId}-title`} className="t-admin-section text-fg-primary">
                    {t('products.tab.variants')}
                </h2>

                {value.options.length === 0 && <p className="t-admin-body text-fg-secondary">{t('products.matrix.noAttributes')}</p>}

                {value.options.map((option) => {
                    const attribute = attributes.find((a) => a.id === option.attribute_id);
                    if (!attribute) return null;
                    const remaining = attribute.values.filter((v) => !option.value_ids.includes(v.id));
                    return (
                        <div key={option.attribute_id} className="flex flex-wrap items-center gap-2">
                            <span className="flex h-8 w-40 items-center rounded-sm border border-line-default bg-surface px-3 t-admin-body text-fg-primary">{name(attribute)}</span>
                            {attribute.values
                                .filter((v) => option.value_ids.includes(v.id))
                                .map((v) => (
                                    <span key={v.id} className="inline-flex items-center gap-1 rounded-xs border border-line-default bg-subtle py-1 pr-2 pl-2.5 t-admin-caption-strong text-fg-primary">
                                        <span lang={bn && v.value_bn ? 'bn' : undefined}>{bn ? (v.value_bn ?? v.value) : v.value}</span>
                                        <button
                                            type="button"
                                            disabled={disabled}
                                            onClick={() => removeValue(attribute.id, v.id)}
                                            aria-label={t('products.matrix.removeValue', { value: v.value })}
                                            className="text-fg-tertiary hover:text-fg-primary disabled:cursor-not-allowed"
                                        >
                                            <XIcon size={12} aria-hidden />
                                        </button>
                                    </span>
                                ))}
                            {remaining.length > 0 && (
                                <label className={`relative focus-within:shadow-focus ${buttonClass('ghost', 'sm')}`}>
                                    <PlusIcon size={16} aria-hidden />
                                    {t('products.matrix.addValue')}
                                    <select
                                        aria-label={t('products.matrix.addValueTo', { attribute: name(attribute) })}
                                        value=""
                                        disabled={disabled || !canPrice}
                                        onChange={(e) => e.target.value && addValue(attribute.id, Number(e.target.value))}
                                        className="absolute inset-0 cursor-pointer opacity-0 disabled:cursor-not-allowed"
                                    >
                                        <option value="">{t('products.matrix.addValue')}</option>
                                        {remaining.map((v) => (
                                            <option key={v.id} value={v.id}>
                                                {bn ? (v.value_bn ?? v.value) : v.value}
                                            </option>
                                        ))}
                                    </select>
                                </label>
                            )}
                            <span className="ms-auto">
                                <IconButton
                                    size="sm"
                                    disabled={disabled}
                                    onClick={() => setOptions(value.options.filter((o) => o.attribute_id !== attribute.id))}
                                    aria-label={t('products.matrix.removeAttribute', { attribute: name(attribute) })}
                                >
                                    <TrashIcon size={16} aria-hidden />
                                </IconButton>
                            </span>
                        </div>
                    );
                })}

                {canAddAttribute && (
                    <label className={`relative w-fit focus-within:shadow-focus ${buttonClass('outline', 'sm')}`}>
                        <PlusIcon size={16} aria-hidden />
                        {t('products.matrix.addAttribute')}
                        <select
                            aria-label={t('products.matrix.addAttribute')}
                            value=""
                            disabled={disabled || !canPrice}
                            onChange={(e) => e.target.value && setOptions([...value.options, { attribute_id: Number(e.target.value), value_ids: [] }])}
                            className="absolute inset-0 cursor-pointer opacity-0 disabled:cursor-not-allowed"
                        >
                            <option value="">{t('products.matrix.addAttribute')}</option>
                            {freeAttributes.map((a) => (
                                <option key={a.id} value={a.id}>
                                    {name(a)}
                                </option>
                            ))}
                        </select>
                    </label>
                )}
                {!canPrice && <p className="t-admin-caption text-fg-tertiary">{t('products.matrix.priceLocked')}</p>}
            </div>

            <div className="flex flex-wrap items-center gap-3 bg-brand-subtle px-5 py-3">
                <p className="min-w-0 flex-1 t-admin-body text-fg-primary" aria-live="polite">
                    {t('products.matrix.summary', { attributes: value.options.length, count: combos.length })}
                </p>
                {tooMany && (
                    <p className="flex items-center gap-1.5 t-admin-caption-strong text-feedback-danger">
                        <WarningCircleIcon size={14} weight="fill" aria-hidden />
                        {t('products.matrix.tooMany', { max: MAX_VARIANTS })}
                    </p>
                )}
            </div>

            {matrixErrors.length > 0 && (
                <div role="alert" className="flex flex-col gap-1 border-t border-line-default bg-danger-subtle px-5 py-3">
                    {matrixErrors.map((message) => (
                        <p key={message} className="flex items-center gap-1.5 t-admin-caption-strong text-fg-primary">
                            <WarningCircleIcon size={14} weight="fill" aria-hidden className="text-feedback-danger" />
                            {message}
                        </p>
                    ))}
                </div>
            )}

            {combos.length > 0 && (
                <>
                    <div className="flex flex-wrap items-center gap-3 border-t border-line-default px-4 py-2">
                        <label htmlFor={`${bulkId}-field`} className="t-admin-body text-fg-secondary">
                            {t('products.matrix.bulkSet')}
                        </label>
                        <Select
                            id={`${bulkId}-field`}
                            size="sm"
                            value={bulkField}
                            onChange={(e) => setBulkField(e.target.value as BulkField)}
                            disabled={disabled}
                            className="w-36"
                        >
                            {bulkFields
                                .filter((f) => f.allowed)
                                .map((f) => (
                                    <option key={f.value} value={f.value}>
                                        {f.label}
                                    </option>
                                ))}
                        </Select>
                        <div className="w-28">
                            <input
                                aria-label={t('products.matrix.bulkValue')}
                                value={bulkValue}
                                onChange={(e) => setBulkValue(e.target.value)}
                                disabled={disabled}
                                inputMode="decimal"
                                className={`${controlHeight.sm} ${inputClass} text-end tabular`}
                            />
                        </div>
                        <span className="t-admin-body text-fg-secondary">
                            {selected.size > 0 ? t('products.matrix.forSelected', { count: selected.size }) : t('products.matrix.forAll', { count: combos.length })}
                        </span>
                        <Button size="sm" onClick={applyBulk} disabled={disabled || bulkValue.trim() === ''}>
                            {t('products.matrix.apply')}
                        </Button>
                    </div>

                    <div className="overflow-x-auto">
                        <table className="w-full border-collapse">
                            <thead className="border-y border-line-strong bg-subtle">
                                <tr className="text-left">
                                    <th scope="col" className="w-10 px-3 py-2.5">
                                        <input type="checkbox" checked={allSelected} onChange={toggleAll} aria-label={t('products.matrix.selectAll')} className="size-4 accent-brand" />
                                    </th>
                                    <Th>{t('products.matrix.on')}</Th>
                                    <Th>{t('products.matrix.variant')}</Th>
                                    <Th>{t('products.field.sku')}</Th>
                                    <Th end>{t('products.field.price')}</Th>
                                    <Th end>{t('products.field.compareAt')}</Th>
                                    {canCost && <Th end>{t('products.field.cost')}</Th>}
                                    <Th end>{t('products.field.weight')}</Th>
                                    <Th>{t('products.field.barcode')}</Th>
                                </tr>
                            </thead>
                            <tbody>
                                {combos.map((combo) => {
                                    const row = rowOf(combo);
                                    const rowErrors = errors[combo.key];
                                    const off = row.status === 'archived';
                                    const label = bn ? combo.labelBn : combo.label;
                                    return (
                                        <MatrixRows key={combo.key} errors={rowErrors} columns={columnCount} labels={{ sku: t('products.field.sku'), barcode: t('products.field.barcode'), price: t('products.field.price'), compare_at_price: t('products.field.compareAt'), cost_price: t('products.field.cost'), wholesale_price: t('products.field.wholesale'), weight_grams: t('products.field.weight') }}>
                                            <td className={`w-10 px-3 py-2 ${rowErrors ? 'border-l-2 border-line-danger' : ''}`}>
                                                <input type="checkbox" checked={selected.has(combo.key)} onChange={() => toggleOne(combo.key)} aria-label={t('products.matrix.select', { variant: label })} className="size-4 accent-brand" />
                                            </td>
                                            <td className="px-3 py-2">
                                                <Toggle checked={!off} disabled={disabled} label={t('products.matrix.enabled', { variant: label })} onChange={(on) => patchRow(combo, { status: on ? 'active' : 'archived' })} />
                                            </td>
                                            <td className="px-3 py-2">
                                                <p lang={bn ? 'bn' : undefined} className={`t-admin-body-strong whitespace-nowrap ${off ? 'text-fg-tertiary' : 'text-fg-primary'}`}>
                                                    {label}
                                                </p>
                                                <p className="t-admin-caption whitespace-nowrap text-fg-tertiary">
                                                    {off ? t('products.matrix.disabled') : bn ? combo.attributeNamesBn : combo.attributeNames}
                                                </p>
                                            </td>
                                            <td className="px-3 py-2">{cell(combo, row, 'sku', t('products.field.sku'))}</td>
                                            <td className="px-3 py-2">{cell(combo, row, 'price', t('products.field.price'))}</td>
                                            <td className="px-3 py-2">{cell(combo, row, 'compare_at_price', t('products.field.compareAt'))}</td>
                                            {canCost && <td className="px-3 py-2">{cell(combo, row, 'cost_price', t('products.field.cost'))}</td>}
                                            <td className="px-3 py-2">{cell(combo, row, 'weight_grams', t('products.field.weight'))}</td>
                                            <td className="px-3 py-2">{cell(combo, row, 'barcode', t('products.field.barcode'))}</td>
                                        </MatrixRows>
                                    );
                                })}
                            </tbody>
                        </table>
                    </div>
                    <p className="border-t border-line-default px-5 py-3 t-admin-caption text-fg-secondary">
                        {t('products.matrix.footer', { count: combos.length, enabled: enabledCount })}
                    </p>
                </>
            )}

            {outside.length > 0 && (
                <div className="flex flex-col gap-2 border-t border-line-default bg-subtle px-5 py-4">
                    <h3 className="t-admin-body-strong text-fg-primary">{t('products.matrix.archivedTitle')}</h3>
                    <p className="t-admin-caption text-fg-tertiary">{t('products.matrix.archivedHint')}</p>
                    <ul className="flex flex-col gap-1">
                        {outside.map(([key, row]) => (
                            <li key={key} className="flex items-center gap-3 t-admin-body text-fg-tertiary">
                                <ArrowCounterClockwiseIcon size={14} aria-hidden />
                                <span>{labelFor(row.value_ids, attributes, bn)}</span>
                                <span className="t-admin-mono-sm">{row.sku}</span>
                            </li>
                        ))}
                    </ul>
                </div>
            )}
        </section>
    );
}

function Th({ children, end }: { children: ReactNode; end?: boolean }) {
    return (
        <th scope="col" className={`h-9 px-3 t-admin-overline whitespace-nowrap text-fg-secondary ${end ? 'text-end' : 'text-start'}`}>
            {children}
        </th>
    );
}

/** A grid row plus, when it is invalid, the row-spanning error strip beneath it (A9 `invalid`). */
function MatrixRows({ children, errors, columns, labels }: { children: ReactNode; errors?: PlacedErrors['rows'][string]; columns: number; labels: Record<keyof VariantFields, string> }) {
    const messages = errors ? Object.entries(errors).map(([field, message]) => (field === 'row' ? message : `${labels[field as keyof VariantFields]}: ${message}`)) : [];
    return (
        <>
            <tr className={messages.length > 0 ? '' : 'border-b border-line-default'}>{children}</tr>
            {messages.length > 0 && (
                <tr className="border-b border-line-default bg-subtle">
                    <td colSpan={columns} className="border-l-2 border-line-danger px-3 py-1.5">
                        {messages.map((message) => (
                            <p key={message} className="flex items-center gap-1.5 t-admin-caption-strong text-fg-primary">
                                <WarningCircleIcon size={14} weight="fill" aria-hidden className="shrink-0 text-feedback-danger" />
                                {message}
                            </p>
                        ))}
                    </td>
                </tr>
            )}
        </>
    );
}
