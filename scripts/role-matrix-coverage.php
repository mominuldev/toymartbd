<?php

declare(strict_types=1);

/*
 * Role-matrix coverage (CLAUDE.md rule 21) — see tests/Support/RoleMatrixCoverage.php.
 *
 *   ROLE_MATRIX_COVERAGE_FILE=/tmp/rm.log php artisan test --parallel
 *   php scripts/role-matrix-coverage.php verify /tmp/rm.log   # CI: registry ⊆ recorded
 *   php scripts/role-matrix-coverage.php write  /tmp/rm.log   # regenerate the registry
 *
 * `verify` fails when the registry lists an admin route that no RoleMatrix
 * assertion reached during the run — a claimed-but-untested route. `write` keeps
 * only admin route names (api.v1.admin.*) and sorts them.
 */

$registryPath = dirname(__DIR__).'/tests/Support/role-matrix-routes.php';

[$self, $mode, $log] = $argv + [null, null, null];

if (! in_array($mode, ['verify', 'write'], true) || ! is_string($log) || ! is_file($log)) {
    fwrite(STDERR, "usage: php {$self} verify|write <coverage-log>\n");
    exit(2);
}

$recorded = array_values(array_unique(array_filter(
    array_map('trim', file($log) ?: []),
    static fn (string $name): bool => str_starts_with($name, 'api.v1.admin.'),
)));
sort($recorded);

if ($mode === 'write') {
    $body = "<?php\n\ndeclare(strict_types=1);\n\n"
        ."// Admin routes with a 403 role-matrix test. Generated by scripts/role-matrix-coverage.php;\n"
        ."// checked by tests/Arch/AdminRouteAuthorisationTest.php and, in CI, against a recorded run.\n\n"
        ."return [\n";
    foreach ($recorded as $name) {
        $body .= "    '{$name}',\n";
    }
    file_put_contents($registryPath, $body."];\n");
    echo count($recorded)." admin routes written to the registry.\n";
    exit(0);
}

/** @var list<string> $registry */
$registry = require $registryPath;
$unproven = array_values(array_diff($registry, $recorded));

if ($unproven !== []) {
    fwrite(STDERR, "The role-matrix registry lists routes no RoleMatrix test reached:\n  ".implode("\n  ", $unproven)."\n");
    exit(1);
}

echo count($registry)." registered admin routes, every one reached by a RoleMatrix test.\n";
