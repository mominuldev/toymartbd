#!/usr/bin/env node
// Builds the design tokens from the Figma export in src/figma-variables.json.
//
//   dist/tokens.css     runtime custom properties (--tm-*), one block per theme, plus type classes
//   dist/tailwind.css   Tailwind v4 @theme mapping utilities onto the runtime properties
//   dist/tokens.json    every colour resolved to hex, per theme
//   src/generated.ts    typed token names for TypeScript
//
// No dependencies on purpose: this runs before `npm install` finishes in CI.
// `--check` regenerates in memory and exits 1 if any committed output is stale.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(join(root, 'src/figma-variables.json'), 'utf8'));
const check = process.argv.includes('--check');

// Figma mode name → data-theme value. Light is also the :root default.
const THEMES = [
  ['Light', 'light'],
  ['Dark', 'dark'],
  ['Admin Light', 'admin-light'],
  ['Admin Dark', 'admin-dark'],
];

const slug = (name) => name.replaceAll('/', '-');
const rem = (px) => `${+(px / 16).toFixed(4)}rem`;
const pct = (v) => +(v / 100).toFixed(3);

// ---------- colour resolution ----------
const primitives = src.collections.Primitives.vars;
const color = src.collections.Color;

function resolve(value) {
  if (value.startsWith('{')) {
    const hex = primitives[value.slice(1, -1)];
    if (!hex) throw new Error(`Unknown primitive ${value}`);
    return hex;
  }
  return value;
}

function cssColor(hex) {
  if (hex.length === 9) {
    const [r, g, b, a] = [1, 3, 5, 7].map((i) => parseInt(hex.slice(i, i + 2), 16));
    return `rgb(${r} ${g} ${b} / ${+(a / 255).toFixed(2)})`;
  }
  return hex;
}

// ---------- contrast gate (WCAG 2.2 AA) ----------
function luminance(hex) {
  const c = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
}
function ratio(a, b) {
  const [x, y] = [luminance(a), luminance(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
}

const TEXT = 4.5;
const UI = 3;
const PAIRS = [
  ...['primary', 'secondary', 'tertiary'].flatMap((t) =>
    ['canvas', 'surface', 'subtle'].map((b) => [`color/text/${t}`, `color/bg/${b}`, TEXT])),
  ['color/text/link', 'color/bg/surface', TEXT],
  ['color/text/brand', 'color/bg/surface', TEXT],
  ['color/text/discount', 'color/bg/surface', TEXT],
  ['color/text/on-brand', 'color/bg/brand', TEXT],
  ['color/text/on-accent', 'color/bg/accent', TEXT],
  ['color/text/on-teal', 'color/bg/teal', TEXT],
  ['color/text/on-grape', 'color/bg/grape', TEXT],
  ['color/text/on-danger', 'color/bg/danger', TEXT],
  ...['success', 'warning', 'danger', 'info'].map((f) => [`color/feedback/${f}`, 'color/bg/surface', TEXT]),
  ...['success', 'warning', 'danger', 'info'].map((f) => [`color/feedback/${f}`, `color/bg/${f}-subtle`, TEXT]),
  ...['in-stock', 'low-stock', 'out-of-stock'].map((s) => [`color/status/${s}`, 'color/bg/surface', TEXT]),
  ['color/border/strong', 'color/bg/surface', UI],
  ['color/border/focus', 'color/bg/surface', UI],
];

// ---------- outputs ----------
const resolved = {};
const failures = [];
const css = [];
const header = '/* Generated by packages/tokens/scripts/build.mjs from the Figma export. Do not edit. */\n';

// Static (theme-independent) properties.
const staticVars = [];
for (const [name, hex] of Object.entries(primitives)) staticVars.push(`--tm-palette-${slug(name)}: ${cssColor(hex)};`);
for (const [name, px] of Object.entries(src.collections.Spacing)) staticVars.push(`--tm-${slug(name)}: ${px}px;`);
for (const [name, px] of Object.entries(src.collections.Radius)) staticVars.push(`--tm-${slug(name)}: ${px}px;`);
const fam = src.collections.Typography.families;
const FALLBACK = { latin: 'ui-sans-serif, system-ui, sans-serif', bangla: '"Noto Sans Bengali UI", sans-serif', mono: 'ui-monospace, monospace' };
for (const [k, f] of Object.entries(fam)) {
  const fb = k.includes('bangla') ? FALLBACK.bangla : k === 'mono' ? FALLBACK.mono : FALLBACK.latin;
  staticVars.push(`--tm-font-${k}: "${f}", ${fb};`);
}
for (const [k, ms] of Object.entries(src.motion.duration)) staticVars.push(`--tm-duration-${k}: ${ms}ms;`);
for (const [k, e] of Object.entries(src.motion.easing)) staticVars.push(`--tm-ease-${k}: ${e};`);
for (const [k, [a, b]] of Object.entries(src.gradients)) staticVars.push(`--tm-gradient-${k}: linear-gradient(135deg, ${a} 0%, ${b} 100%);`);
css.push(`:root {\n  ${staticVars.join('\n  ')}\n}`);

// One block per theme. Themes nest: the admin sidebar sets data-theme="admin-dark"
// inside an admin-light page, which works because every value is set directly here.
const shadow = (layers) => layers
  .map(([inset, x, y, blur, spread, hex]) => `${inset ? 'inset ' : ''}${x}px ${y}px ${blur}px ${spread}px ${cssColor(hex)}`)
  .join(', ');

color.modes.forEach((mode, i) => {
  const theme = THEMES.find(([m]) => m === mode)?.[1];
  if (!theme) throw new Error(`No theme mapping for mode ${mode}`);
  resolved[theme] = {};
  const lines = [`color-scheme: ${theme.endsWith('dark') ? 'dark' : 'light'};`];
  for (const [name, values] of Object.entries(color.vars)) {
    const hex = resolve(values[i]);
    resolved[theme][name] = hex;
    lines.push(`--tm-${slug(name)}: ${cssColor(hex)};`);
  }
  for (const [k, layers] of Object.entries(src.elevation[mode])) lines.push(`--tm-elevation-${k}: ${shadow(layers)};`);
  lines.push('--tm-focus-ring: 0 0 0 2px var(--tm-color-bg-surface), 0 0 0 4px var(--tm-color-border-focus);');
  const selector = theme === 'light' ? ':root, [data-theme="light"]' : `[data-theme="${theme}"]`;
  css.push(`${selector} {\n  ${lines.join('\n  ')}\n}`);

  for (const [fg, bg, min] of PAIRS) {
    const r = ratio(resolved[theme][fg], resolved[theme][bg]);
    if (r < min) failures.push(`${theme}: ${fg} on ${bg} = ${r.toFixed(2)} (needs ${min})`);
  }
});

// ---------- type classes ----------
// Bangla twins apply under :lang(bn) or .lang-bn (CLAUDE.md rule 38) — never one
// global line-height for both scripts.
const bnSel = (cls) => `.${cls}:lang(bn), .lang-bn .${cls}, .${cls}.lang-bn`;
const typeRule = ([family, weight, size, lh, tracking, upper], trackingUnit) => [
  `font-family: var(--tm-font-${family});`,
  `font-weight: ${weight};`,
  `font-size: ${rem(size)};`,
  `line-height: ${pct(lh)};`,
  `letter-spacing: ${trackingUnit === '%' ? `${pct(tracking)}em` : `${tracking}px`};`,
  ...(upper ? ['text-transform: uppercase;'] : []),
].join(' ');

const typeCss = [];
for (const [name, spec] of Object.entries(src.adminText.en)) {
  typeCss.push(`.t-admin-${name} { ${typeRule(spec, '%')} }`);
  const bn = src.adminText.bn[name];
  if (bn) typeCss.push(`${bnSel(`t-admin-${name}`)} { ${typeRule(bn, '%')} text-transform: none; }`);
}
const typo = src.collections.Typography;
const desktopQuery = `@media (min-width: ${rem(src.breakpoints.lg)})`;
const desktop = [];
for (const [name, [mob, desk, wl, wb, lhl, lhb, tr]] of Object.entries(typo.scale)) {
  const display = typo.display.includes(name);
  const upper = name === 'overline';
  typeCss.push(`.t-${name} { ${typeRule([display ? 'display-latin' : 'latin', wl, mob, lhl, tr, upper], 'px')} }`);
  typeCss.push(`${bnSel(`t-${name}`)} { ${typeRule([display ? 'display-bangla' : 'bangla', wb, name === 'overline' ? 12 : mob, lhb, 0, false], 'px')} text-transform: none; }`);
  // The Bangla selector outranks the bare class, so it must be listed here too.
  if (desk !== mob) desktop.push(`.t-${name}, ${bnSel(`t-${name}`)} { font-size: ${rem(desk)}; }`);
}
typeCss.push(`${desktopQuery} {\n  ${desktop.join('\n  ')}\n}`);
css.push(`@layer components {\n${typeCss.join('\n')}\n}`);

// ---------- Tailwind v4 theme ----------
// bg/* → bg-canvas, bg-brand …   text/* → text-fg-primary …   border/* → border-line-default …
// status/* and feedback/* keep their group: text-feedback-danger, text-status-low-stock.
const twColor = (name) => {
  const [, group, key] = name.split('/');
  if (group === 'bg') return `--color-${key}`;
  if (group === 'text') return `--color-fg-${key}`;
  if (group === 'border') return `--color-line-${key}`;
  return `--color-${group}-${key}`;
};
const twInline = [
  ...Object.keys(color.vars).map((n) => `${twColor(n)}: var(--tm-${slug(n)});`),
  ...Object.keys(src.elevation.Light).map((k) => `--shadow-${k}: var(--tm-elevation-${k});`),
  '--shadow-focus: var(--tm-focus-ring);',
  ...Object.keys(fam).map((k) => `--font-${k === 'latin' ? 'sans' : k}: var(--tm-font-${k});`),
  ...Object.keys(src.motion.easing).map((k) => `--ease-${k}: var(--tm-ease-${k});`),
];
const sp = src.collections.Spacing;
const twStatic = [
  '--color-*: initial;',
  '--spacing: 0.25rem;',
  ...Object.entries(src.collections.Radius).map(([n, px]) => `--${n.replace('/', '-')}: ${px === 9999 ? 'calc(infinity * 1px)' : `${px}px`};`),
  ...Object.entries(src.breakpoints).map(([k, px]) => `--breakpoint-${k}: ${rem(px)};`),
  `--container-content: ${rem(sp['layout/container-max'])};`,
  ...['gutter-mobile', 'gutter-tablet', 'gutter-desktop', 'section-mobile', 'section-desktop'].map((k) => `--spacing-${k}: ${rem(sp[`layout/${k}`])};`),
  ...['touch-min', 'control-sm', 'control-md', 'control-lg', 'icon-sm', 'icon-md', 'icon-lg', 'icon-category'].map((k) => `--spacing-${k}: ${rem(sp[`size/${k}`])};`),
];
const tailwind = `${header}/* Import after "tailwindcss" and @toymart/tokens/css. Palette primitives are deliberately not utilities:
   components use semantic tokens only (CLAUDE.md rule 26). */
@theme {
  ${twStatic.join('\n  ')}
}

@theme inline {
  ${twInline.join('\n  ')}
}

/* dark: follows the data-theme attribute, not the OS, so a dark region (the admin
   sidebar) inside a light page resolves correctly. Tokens already switch per theme;
   reach for dark: only for non-colour differences. */
@custom-variant dark (&:where([data-theme$="dark"], [data-theme$="dark"] *));
`;

// ---------- TypeScript names ----------
const ts = `// Generated by packages/tokens/scripts/build.mjs. Do not edit.
export const colorTokens = ${JSON.stringify(Object.keys(color.vars), null, 2)} as const;
export type ColorToken = (typeof colorTokens)[number];
export const resolvedColors: Record<'light' | 'dark' | 'admin-light' | 'admin-dark', Record<ColorToken, string>> = ${JSON.stringify(resolved, null, 2)};
`;

if (failures.length) {
  console.error(`Contrast gate failed (${failures.length}):\n  ${failures.join('\n  ')}`);
  process.exit(1);
}

const outputs = {
  'dist/tokens.css': `${header}${css.join('\n\n')}\n`,
  'dist/tailwind.css': tailwind,
  'dist/tokens.json': `${JSON.stringify(resolved, null, 2)}\n`,
  'src/generated.ts': ts,
};

let stale = false;
for (const [path, body] of Object.entries(outputs)) {
  const file = join(root, path);
  if (check) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== body) { console.error(`stale: ${path}`); stale = true; }
    continue;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, body);
  console.log(`wrote ${path}`);
}
if (stale) process.exit(1);
console.log(`contrast: ${PAIRS.length * color.modes.length} pairs pass AA`);
