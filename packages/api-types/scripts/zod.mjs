#!/usr/bin/env node
// Generates Zod schemas for every request body in docs/api/openapi.json (CLAUDE.md
// rule 27: admin form schemas come from OpenAPI, never written twice by hand).
//
// Scope is deliberately the subset Scramble emits for FormRequests: objects of
// strings, numbers, integers, booleans, enums, arrays and $refs, with 3.1-style
// nullable unions. Anything else fails loudly, so an unsupported rule is noticed
// instead of silently validating nothing.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(readFileSync(join(root, '../../docs/api/openapi.json'), 'utf8'));
const schemas = spec.components?.schemas ?? {};

const requestNames = Object.keys(schemas).filter((name) => name.endsWith('Request')).sort();

function zodFor(schema, path) {
    if (schema.$ref) {
        const name = schema.$ref.split('/').pop();
        return `${camel(name)}Schema`;
    }

    // OpenAPI 3.1: type may be ["string", "null"].
    const types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : [];
    // A nullable enum/ref arrives as anyOf: [{$ref}, {type: 'null'}] — keep the null.
    const nullable =
        types.includes('null') || schema.nullable === true || (schema.anyOf ?? schema.oneOf ?? []).some((s) => s.type === 'null');
    const type = types.find((t) => t !== 'null');

    let out;
    if (schema.enum) {
        const values = schema.enum.filter((v) => v !== null);
        out = values.every((v) => typeof v === 'string')
            ? `z.enum(${JSON.stringify(values)})`
            : `z.union([${values.map((v) => `z.literal(${JSON.stringify(v)})`).join(', ')}])`;
    } else if (schema.anyOf || schema.oneOf) {
        const parts = (schema.anyOf ?? schema.oneOf).filter((s) => s.type !== 'null');
        out = parts.length === 1 ? zodFor(parts[0], path) : `z.union([${parts.map((s, i) => zodFor(s, `${path}|${i}`)).join(', ')}])`;
    } else if (type === 'string' && schema.format === 'binary') {
        // A multipart upload field: a File/Blob in the browser, never a string.
        out = 'z.instanceof(Blob)';
    } else if (type === 'string') {
        out = 'z.string()';
        if (schema.format === 'email') out = 'z.email()';
        else if (schema.format === 'uri') out = 'z.url()';
        if (schema.minLength !== undefined) out += `.min(${schema.minLength})`;
        if (schema.maxLength !== undefined) out += `.max(${schema.maxLength})`;
        if (schema.pattern) out += `.regex(new RegExp(${JSON.stringify(schema.pattern)}))`;
    } else if (type === 'integer' || type === 'number') {
        out = type === 'integer' ? 'z.number().int()' : 'z.number()';
        if (schema.minimum !== undefined) out += `.min(${schema.minimum})`;
        if (schema.maximum !== undefined) out += `.max(${schema.maximum})`;
    } else if (type === 'boolean') {
        out = 'z.boolean()';
    } else if (type === 'array') {
        out = `z.array(${schema.items ? zodFor(schema.items, `${path}[]`) : 'z.unknown()'})`;
        if (schema.minItems !== undefined) out += `.min(${schema.minItems})`;
        if (schema.maxItems !== undefined) out += `.max(${schema.maxItems})`;
    } else if (type === 'object' && !schema.properties && schema.additionalProperties && typeof schema.additionalProperties === 'object') {
        // A string-keyed map (e.g. product specifications).
        out = `z.record(z.string(), ${zodFor(schema.additionalProperties, `${path}{}`)})`;
    } else if (type === 'object') {
        const required = new Set(schema.required ?? []);
        const fields = Object.entries(schema.properties ?? {}).map(([key, prop]) => {
            let inner = zodFor(prop, `${path}.${key}`);
            // Laravel's `required` rejects '' (and the TrimStrings middleware turns
            // whitespace into ''), while OpenAPI's `required` only means "key present".
            // Mirror the server: a required string must be non-empty.
            if (required.has(key) && /^z\.(string|email|url)\(\)/.test(inner) && !/\.min\(/.test(inner)) {
                inner = inner.replace(/^(z\.(?:string|email|url)\(\))/, '$1.min(1)');
            }
            return `    ${JSON.stringify(key)}: ${inner}${required.has(key) ? '' : '.optional()'},`;
        });
        out = `z.object({\n${fields.join('\n')}\n})`;
    } else if (Object.keys(schema).length === 0) {
        // `{}`: any JSON value (e.g. the values of a free-form JSON-LD override).
        out = 'z.unknown()';
    } else {
        throw new Error(`Unsupported schema at ${path}: ${JSON.stringify(schema)}`);
    }

    return nullable ? `${out}.nullable()` : out;
}

function camel(name) {
    return name.charAt(0).toLowerCase() + name.slice(1);
}

const lines = [
    '// Generated by packages/api-types/scripts/zod.mjs from docs/api/openapi.json. Do not edit.',
    "import { z } from 'zod';",
    '',
];

// Non-request components a request $refs (e.g. a PHP enum used with Rule::enum) are
// emitted first, so the request schemas can reference them by name.
const referenced = new Set();
function collectRefs(node) {
    if (Array.isArray(node)) return node.forEach(collectRefs);
    if (node === null || typeof node !== 'object') return;
    if (typeof node.$ref === 'string') {
        const name = node.$ref.split('/').pop();
        if (!requestNames.includes(name) && !referenced.has(name)) {
            referenced.add(name);
            collectRefs(schemas[name]);
        }
    }
    Object.values(node).forEach(collectRefs);
}
requestNames.forEach((name) => collectRefs(schemas[name]));

for (const name of [...referenced].sort()) {
    const schema = schemas[name];
    if (!schema) throw new Error(`Unresolved $ref: ${name}`);
    lines.push(`export const ${camel(name)}Schema = ${zodFor(schema, name)};`);
    lines.push(`export type ${name} = z.infer<typeof ${camel(name)}Schema>;`);
    lines.push('');
}

for (const name of requestNames) {
    const schema = schemas[name];
    const doc = schema.description ? `/** ${schema.description.replace(/\*\//g, '*\\/').split('\n')[0]} */\n` : '';
    lines.push(`${doc}export const ${camel(name)}Schema = ${zodFor(schema, name)};`);
    lines.push(`export type ${name}Input = z.input<typeof ${camel(name)}Schema>;`);
    lines.push('');
}

writeFileSync(join(root, 'src/zod.ts'), lines.join('\n'));
console.log(`zod: ${requestNames.length} request schemas, ${referenced.size} referenced schemas → src/zod.ts`);
