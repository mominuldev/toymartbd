<?php

declare(strict_types=1);

/*
|--------------------------------------------------------------------------
| Media pipeline (P4-CAT-07)
|--------------------------------------------------------------------------
|
| Every upload is validated by its content (magic bytes), decoded and re-encoded
| through Intervention — which drops EXIF/XMP/ICC metadata and anything embedded
| after the image data — then rendered as WebP and AVIF at the widths below.
|
| - `originals_disk` holds the sanitised master (re-encoded, never the raw upload)
|   privately, so a rendition can be regenerated or re-cropped later.
| - `disk` holds the public renditions. Paths carry a random id per upload, so a
|   file never changes after it is written and the CDN may cache it forever.
| - `cdn_url`, when set, replaces the disk's own URL as the public base
|   (e.g. https://media.toymartbd.com). Unset in development: the `public` disk
|   URL (APP_URL/storage) is used.
|
| Widths (UI-UX-DESIGN-SPEC §5/§7): 160 admin/cart thumbnail · 320 tile @2x and
| mobile card @1x · 480 product card (2-up mobile @2x, 4-up desktop) · 800 PDP on
| tablets · 1200 PDP gallery @2x and the upload minimum. Never upscaled: a source
| narrower than a width stops the list at its own width.
*/

return [
    'disk' => env('MEDIA_DISK', 'public'),

    'originals_disk' => env('MEDIA_ORIGINALS_DISK', 'local'),

    'cdn_url' => env('MEDIA_CDN_URL'),

    'widths' => [160, 320, 480, 800, 1200],

    /** Named sizes the admin resource exposes as `urls`. */
    'sizes' => [
        'thumb' => 320,
        'medium' => 480,
        'large' => 1200,
    ],

    'formats' => ['webp', 'avif'],

    'quality' => [
        'webp' => (int) env('MEDIA_QUALITY_WEBP', 80),
        'avif' => (int) env('MEDIA_QUALITY_AVIF', 60),
        'master' => 92,
    ],

    /** Upload limits — the server is authoritative; the admin repeats them for UX only. */
    'max_bytes' => 10 * 1024 * 1024,
    'max_dimension' => 8000,

    /** Images per product (Figma ImageUploader: "Images (3 of 10)"). */
    'max_per_product' => 10,

    /** Real (sniffed) types accepted. SVG, GIF, HEIC and everything else are refused. */
    'accepted_types' => ['image/jpeg', 'image/png', 'image/webp', 'image/avif'],

    /** Renditions are generated by a queued job on this queue, after commit. */
    'queue' => env('MEDIA_QUEUE', 'index'),

    /**
     * Whether DemoCatalogSeeder (local/testing only) attaches the Figma product photos
     * (docs/_design/assets/products) through the upload pipeline. Unset: on in `local`,
     * off everywhere else — PHPUnit and the E2E seeds stay fast without 16 × 9 encodes.
     */
    'demo_seed_images' => env('DEMO_SEED_IMAGES'),
];
